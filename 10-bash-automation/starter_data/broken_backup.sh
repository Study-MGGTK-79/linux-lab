#!/bin/bash
# ==============================================================================
# ВНИМАНИЕ: Это проблемный учебный скрипт с грубыми ошибками и антипаттернами!
# Задача студента: провести аудит, выявить все уязвимости и написать безопасную версию.
# ==============================================================================

# 1. Нет 'set -euo pipefail' - скрипт продолжит работу при любых сбоях
# 2. Хардкод переменных без валидации и кавычек
SOURCE_DIR=$1
BACKUP_DIR=$2
RETENTION_DAYS=$3

echo "Начинаем создание бэкапа..."

# 3. Опасное создание временного каталога (предсказуемое имя, уязвимо к symlink attack)
TMP_DIR=/tmp/backup_workdir
mkdir $TMP_DIR

# 4. Копирование без кавычек (упадет на файлах с пробелами)
cp -r $SOURCE_DIR/* $TMP_DIR/

# 5. Архивация: если архиватор завершится с ошибкой, конвейер вернет 0 (tee вернет 0)
tar -czf $BACKUP_DIR/backup_$(date +%Y%m%d_%H%M%S).tar.gz $TMP_DIR/* | tee /tmp/backup_last.log

# 6. Катастрофическая ошибка: если переменная TMP_DIR случайно окажется пустой, выполнится rm -rf /*
rm -rf $TMP_DIR/*
rmdir $TMP_DIR

# 7. Ротация: потенциальное удаление лишнего, нет проверки числового формата RETENTION_DAYS
echo "Удаление старых копий..."
find $BACKUP_DIR -name "*.tar.gz" -mtime +$RETENTION_DAYS -exec rm -f {} \;

# 8. Отсутствие локов: если запустить скрипт дважды параллельно, они испортят TMP_DIR
# 9. Отсутствие trap: если нажать Ctrl+C во время tar, каталог /tmp/backup_workdir навсегда останется на диске!
# 10. Отсутствие алертов и кодов возврата

echo "Резервное копирование успешно завершено!"
